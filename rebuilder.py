logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class FirmwareRebuilder:
    """Rebuilds and verifies UEFI firmware images, recalculating checksums where possible."""

    def __init__(self):
        pass

    def rebuild(self, firmware_path: str, output_path: str) -> None:
        """Rebuild firmware image and recalculate checksums."""
        logger.info(f"Loading firmware image from {firmware_path}")
        
        with open(firmware_path, "rb") as f:
            firmware = bytearray(f.read())

        logger.info(f"Firmware size: {len(firmware)} bytes ({hex(len(firmware))})")

        # Identify firmware type and rebuild accordingly
        if self._is_uefi_firmware(firmware):
            logger.info("Detected UEFI firmware format")
            self._rebuild_uefi(firmware)
        else:
            logger.warning("Could not definitively identify firmware type; performing basic rebuild...")
            self._rebuild_generic(firmware)

        with open(output_path, "wb") as f:
            f.write(firmware)
        logger.info(f"Rebuilt firmware written to {output_path}")
        
        # Verify rebuilt image
        self._verify_firmware(firmware)
        
        # Generate flashrom command
        self._generate_flashrom_command(output_path)

    def _generate_flashrom_command(self, firmware_path: str) -> None:
        """Generate flashrom command for flashing the rebuilt firmware."""
        # Detect programmer (this is a heuristic - in real use, user would specify)
        programmers = ["ch341a_spi", "dediprog", "internal"]  # Common ones
        
