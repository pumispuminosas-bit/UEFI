    def _verify_firmware(self, firmware: bytearray) -> None:
        """Verify rebuilt firmware integrity."""
        logger.info("Verifying rebuilt firmware...")
        
        # Check for suspicious patterns
        suspicious = [b"MALWARE", b"ROOTKIT", b"ESP32"]
        found_suspicious = False
        
        for sig in suspicious:
            if sig in firmware:
                logger.error(f"SUSPICIOUS PATTERN DETECTED: {sig}")
                found_suspicious = True
        
        if not found_suspicious:
            logger.info("✓ No obvious suspicious patterns detected")

        # Check firmware size
        size_mb = len(firmware) / (1024 * 1024)
        if 0.5 <= size_mb <= 16:
            logger.info(f"✓ Firmware size is reasonable: {size_mb:.2f} MB")
        else:
            logger.warning(f"⚠ Firmware size is unusual: {size_mb:.2f} MB")

        logger.info("Firmware verification complete")

    @staticmethod
    def _calculate_checksum_8(data: bytes) -> int:
        """Calculate 8-bit checksum (sum of all bytes mod 256)."""
        checksum = sum(data) & 0xFF
        return (0x100 - checksum) & 0xFF
